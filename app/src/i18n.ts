/** Polish has three plural forms (1 zadanie, 2–4 zadania, 5+ zadań); English two. */
export const pluralForm = (n: number): 'One' | 'Few' | 'Many' => {
  if (n === 1) return 'One';
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'Few';
  return 'Many';
};

/** Fills {name} placeholders. */
export const format = (template: string, vars?: Record<string, string | number>): string =>
  vars ? template.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`)) : template;
